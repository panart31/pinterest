h3("2.2.2 Разбор запроса")

p("Модуль http/request.py читает данные из сокета порциями и накапливает их "
  "в буфере. Конец заголовков определяется по последовательности CRLF CRLF. "
  "Такой подход не зависит от того, как TCP разбил поток на сегменты: "
  "заголовки могут прийти одним пакетом или по одному байту. Фрагмент "
  "чтения заголовков приведён в листинге {lst:read}.")

listing("read", "Чтение блока заголовков из сокета",
        "def _read_head(conn, max_header):\n"
        "    buffer = b\"\"\n"
        "    while True:\n"
        "        separator = buffer.find(b\"\\r\\n\\r\\n\")\n"
        "        if separator >= 0:\n"
        "            if separator + 4 > max_header:\n"
        "                raise HTTPError(400, \"Слишком большой блок заголовков\")\n"
        "            return buffer[:separator], buffer[separator + 4:]\n"
        "        if len(buffer) > max_header:\n"
        "            raise HTTPError(400, \"Слишком большой блок заголовков\")\n"
        "        chunk = conn.recv(4096)\n"
        "        if not chunk:\n"
        "            if not buffer:\n"
        "                raise HTTPError(400, \"Пустой запрос\")\n"
        "            raise HTTPError(400, \"Соединение закрыто\")\n"
        "        buffer += chunk")

p("После выделения заголовков разбирается стартовая строка: метод, цель "
  "запроса и версия разделяются ровно одним пробелом. Метод проверяется по "
  "набору допустимых символов, версия — по списку поддерживаемых. Цель "
  "должна начинаться с косой черты. Заголовки разбираются по первому "
  "двоеточию, имена приводятся к нижнему регистру, что делает обращение "
  "к ним нечувствительным к регистру. Дублирование Content-Length "
  "рассматривается как ошибка: неоднозначная длина тела позволяет "
  "по-разному интерпретировать запрос на клиенте и сервере.")

p("Тело читается ровно до Content-Length. Если в буфере уже оказалась часть "
  "тела, она используется, а недостающие байты дочитываются из сокета. "
  "Превышение лимита в 6 МБ приводит к ответу 413 ещё до чтения тела. "
  "Наличие заголовка Transfer-Encoding вызывает ответ 400, поскольку "
  "chunked-кодировка сознательно не поддерживается. Query string "
  "разбирается вручную: пары разделяются амперсандом, знак «+» заменяется "
  "пробелом, последовательности %XX декодируются в UTF-8. Собственная "
  "реализация декодирования заняла около двадцати строк и позволила "
  "не использовать urllib.request, запрещённый условиями работы.")

