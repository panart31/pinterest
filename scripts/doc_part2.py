h3("2.2.4 Разбор multipart/form-data")

p("Разбор multipart выполняется по байтам, поэтому бинарные данные не "
  "портятся. Из заголовка Content-Type извлекается boundary, тело делится "
  "по строке --boundary, затем каждая часть разделяется на блок заголовков "
  "и данные по пустой строке. Фрагмент разбора приведён в "
  "листинге {lst:multipart}.")

listing("multipart", "Разбор частей multipart/form-data",
        "delimiter = b\"--\" + boundary.encode(\"latin-1\")\n"
        "segments = body.split(delimiter)\n"
        "if len(segments) < 3:\n"
        "    raise MultipartError(\"Тело не содержит ни одной части\")\n"
        "\n"
        "parts = []\n"
        "for segment in segments[1:-1]:\n"
        "    if segment.startswith(b\"--\"):\n"
        "        break\n"
        "    if not segment.startswith(b\"\\r\\n\"):\n"
        "        raise MultipartError(\"Часть без перевода строки\")\n"
        "    segment = segment[2:]\n"
        "    if segment.endswith(b\"\\r\\n\"):\n"
        "        segment = segment[:-2]\n"
        "    header_block, sep, data = segment.partition(b\"\\r\\n\\r\\n\")\n"
        "    if not sep:\n"
        "        raise MultipartError(\"Нет пустой строки после заголовков\")\n"
        "    headers = _parse_part_headers(header_block)\n"
        "    disposition = headers.get(\"content-disposition\", \"\")\n"
        "    _, params = _split_parameters(disposition)\n"
        "    parts.append(Part(name=params[\"name\"],\n"
        "                      filename=params.get(\"filename\"),\n"
        "                      content_type=headers.get(\"content-type\", \"\"),\n"
        "                      data=data))")

p("Параметры Content-Disposition разбираются автоматом, а не делением по "
  "точке с запятой: имя файла может содержать точку с запятой внутри "
  "кавычек. Поддерживается расширенная форма filename*=UTF-8''…, которую "
  "используют некоторые клиенты. Число частей ограничено, что защищает "
  "сервер от формы с тысячами полей. Если boundary отсутствует или тело "
  "не содержит ни одной части, возвращается ошибка 400.")

h3("2.2.5 Маршрутизация")

p("Маршрутизатор хранит список маршрутов, каждый из которых содержит метод, "
  "шаблон пути, обработчик и признак необходимости сессии. Шаблон делится "
  "на сегменты; сегмент в фигурных скобках считается параметром. При "
  "совпадении пути, но несовпадении метода формируется ответ 405 с "
  "заголовком Allow, при полном отсутствии маршрута — 404. Фрагмент "
  "приведён в листинге {lst:router}.")

listing("router", "Поиск маршрута по методу и пути",
        "def match(self, method, path):\n"
        "    parts = _split_path(path)\n"
        "    allowed = set()\n"
        "    for route in self._routes:\n"
        "        params = _match(route.segments, parts)\n"
        "        if params is None:\n"
        "            continue\n"
        "        if route.method == method.upper():\n"
        "            return route, params\n"
        "        allowed.add(route.method)\n"
        "    if allowed:\n"
        "        raise MethodNotAllowed(sorted(allowed))\n"
        "    raise NotFound(path)")

p("Порядок маршрутов не влияет на результат, потому что шаблоны различаются "
  "числом сегментов. Параметры передаются обработчику словарём, а признак "
  "auth позволяет одним механизмом закрыть все приватные маршруты: проверка "
  "сессии выполняется в Application.dispatch до вызова обработчика. "
  "Благодаря этому обработчики не содержат повторяющейся проверки входа.")

h3("2.2.6 Регистрация и вход")

p("Пароли не хранятся в открытом виде. При регистрации генерируется "
  "случайная соль длиной 16 байт, затем вычисляется PBKDF2-HMAC-SHA256 с "
  "200 000 итераций. Соль и хеш хранятся отдельными полями, поэтому "
  "радужные таблицы неприменимы. Проверка пароля выполняется функцией "
  "hmac.compare_digest, которая сравнивает строки за постоянное время и "
  "не позволяет определить правильный префикс по времени ответа. Фрагмент "
  "приведён в листинге {lst:password}.")

listing("password", "Хеширование и проверка пароля",
        "PBKDF2_ITERATIONS = 200_000\n"
        "SALT_BYTES = 16\n"
        "\n"
        "def hash_password(password):\n"
        "    salt = secrets.token_bytes(SALT_BYTES)\n"
        "    digest = hashlib.pbkdf2_hmac(\"sha256\",\n"
        "                                 password.encode(\"utf-8\"),\n"
        "                                 salt, PBKDF2_ITERATIONS)\n"
        "    return salt.hex(), digest.hex()\n"
        "\n"
        "def verify_password(password, salt_hex, hash_hex):\n"
        "    salt = bytes.fromhex(salt_hex)\n"
        "    expected = bytes.fromhex(hash_hex)\n"
        "    actual = hashlib.pbkdf2_hmac(\"sha256\",\n"
        "                                 password.encode(\"utf-8\"),\n"
        "                                 salt, PBKDF2_ITERATIONS)\n"
        "    return hmac.compare_digest(actual, expected)")

p("Выбор PBKDF2 обусловлен тем, что он входит в стандартную библиотеку "
  "Python и поддерживает настраиваемое число итераций. Число 200 000 "
  "соответствует рекомендациям OWASP для PBKDF2-HMAC-SHA256 и создаёт "
  "заметную задержку при переборе. Один вход занимает около 0,15 с на "
  "демонстрационном ноутбуке, что незаметно для пользователя, но делает "
  "подбор пароля дорогим.")

p("Обработчик регистрации сначала разбирает тело в словарь, затем "
  "валидирует поля, вычисляет соль и хеш и только после этого обращается "
  "к базе. Дубликат определяется по исключению IntegrityError от "
  "уникального индекса, поэтому между проверкой и вставкой нет окна для "
  "гонки.")

p("Регистрация проверяет логин регулярным выражением: от 3 до 32 символов, "
  "латиница, цифры, точка, дефис и подчёркивание. Отображаемое имя может "
  "содержать кириллицу и пробелы, а пароль должен быть не короче шести "
  "символов.")

h3("2.2.7 Сессии и cookie")

p("После успешного входа создаётся сессия: сервер генерирует токен "
  "secrets.token_urlsafe(32) и сохраняет его в таблице sessions вместе с "
  "идентификатором пользователя и сроком действия. Токен передаётся в "
  "cookie mosaic_session с атрибутами HttpOnly, SameSite=Lax, Path=/ и "
  "Max-Age, равным сроку жизни сессии. Фрагмент приведён в "
  "листинге {lst:session}.")

listing("session", "Создание и проверка сессии",
        "def create(self, user_id):\n"
        "    token = secrets.token_urlsafe(32)\n"
        "    self.repository.create_session(\n"
        "        token, user_id, iso_in_days(self.ttl_days))\n"
        "    return token\n"
        "\n"
        "def resolve(self, token):\n"
        "    if not token:\n"
        "        return None\n"
        "    row = self.repository.get_session_user(token)\n"
        "    if row is None:\n"
        "        return None\n"
        "    if parse_iso(row[\"expires_at\"]) <= utc_now():\n"
        "        self.repository.delete_session(token)\n"
        "        return None\n"
        "    return {\"id\": row[\"id\"], \"username\": row[\"username\"],\n"
        "            \"display_name\": row[\"display_name\"]}\n"
        "\n"
        "response.set_cookie(\"mosaic_session\", token,\n"
        "                    max_age=ctx.sessions.ttl_seconds)")

p("Токен не содержит данных пользователя: это случайная строка, поэтому "
  "подделать её без доступа к базе невозможно. Атрибут HttpOnly запрещает "
  "чтение cookie из JavaScript, что снижает последствия XSS. SameSite=Lax "
  "не отправляет cookie при межсайтовых POST-запросах, поэтому сторонний "
  "сайт не может выполнить действие от имени пользователя. При выходе "
  "запись удаляется из таблицы, а клиенту отправляется cookie с Max-Age=0.")

p("Просроченные сессии удаляются при попытке использования и дополнительно "
  "при старте сервера. Это простая стратегия очистки: отдельный фоновый "
  "поток не нужен, а таблица не растёт бесконечно. Срок жизни в семь дней "
  "выбран как компромисс между удобством и безопасностью.")

